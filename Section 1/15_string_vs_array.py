name = "Moamen"
print(name[0])
print(name[-1]) #Last Character
print(name[0:3]) #Substring (from index 0 to index 3)
print(name) # original string not affected by slicing

grades = [10, 20, 30, 40, 50]
print(grades[0:2]) #Slicing (from index 0 to index 2)
print(grades[1:3]) #Slicing (from index 1 to index 3)
print(grades) # original list not modified